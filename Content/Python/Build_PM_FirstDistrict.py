"""Build a repeatable urban greybox district in a dedicated Unreal level.

Run from Unreal Editor: Tools > Execute Python Script.
Requires Python Editor Script Plugin and Editor Scripting Utilities.
This creates blockout geometry from engine primitive meshes only; it does not
pretend to be final photorealistic art. Re-running removes only actors tagged
PM_Generated_Blockout before rebuilding them.
"""
import unreal

TAG = unreal.Name("PM_Generated_Blockout")
MAP_PACKAGE = "/Game/Maps/PM_FirstDistrict"
ROOT_FOLDERS = [
    "/Game/Maps", "/Game/Environment", "/Game/Environment/Blockout",
    "/Game/Environment/Buildings", "/Game/Environment/Roads",
    "/Game/Environment/Props", "/Game/Characters", "/Game/Vehicles",
    "/Game/Materials", "/Game/Textures", "/Game/Audio", "/Game/UI", "/Game/Data",
]

# Open the target map first to avoid writing into an unrelated open level.
if unreal.EditorAssetLibrary.does_asset_exist(MAP_PACKAGE):
    world = unreal.EditorLevelLibrary.load_level(MAP_PACKAGE)
    if not world:
        raise RuntimeError("Could not load existing Mayhem map")
else:
    if not unreal.EditorLevelLibrary.new_level(MAP_PACKAGE):
        raise RuntimeError("Could not create Mayhem map")
    world = unreal.EditorLevelLibrary.get_editor_world()

actor_subsystem = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
cube = unreal.load_asset("/Engine/BasicShapes/Cube.Cube")
cylinder = unreal.load_asset("/Engine/BasicShapes/Cylinder.Cylinder")
sphere = unreal.load_asset("/Engine/BasicShapes/Sphere.Sphere")
if not cube or not cylinder or not sphere:
    raise RuntimeError("Could not load Unreal Engine basic shape meshes.")

for folder in ROOT_FOLDERS:
    unreal.EditorAssetLibrary.make_directory(folder)

# Remove only actors generated by this script; preserve user-authored actors.
removed = 0
for actor in actor_subsystem.get_all_level_actors():
    if TAG in actor.tags:
        actor_subsystem.destroy_actor(actor)
        removed += 1

created = 0

def spawn_mesh(mesh, label, location, scale, rotation=None):
    global created
    actor = actor_subsystem.spawn_actor_from_class(
        unreal.StaticMeshActor,
        unreal.Vector(location[0], location[1], location[2]),
        rotation or unreal.Rotator(0.0, 0.0, 0.0))
    if not actor:
        raise RuntimeError("Failed to spawn actor: " + label)
    component = actor.get_component_by_class(unreal.StaticMeshComponent)
    component.set_static_mesh(mesh)
    actor.set_actor_scale3d(unreal.Vector(scale[0], scale[1], scale[2]))
    actor.set_actor_label(label)
    actor.tags = list(actor.tags) + [TAG]
    created += 1
    return actor

def box(label, x, y, z, sx, sy, sz):
    return spawn_mesh(cube, label, (x, y, z), (sx, sy, sz))

# 300 m x 300 m site base.
box("PM_Ground_Base", 0, 0, -180, 300, 300, 1.5)

# Three streets in each direction, with raised sidewalks.
road_centers = [-10000, 0, 10000]
for index, center in enumerate(road_centers):
    box("PM_Road_NS_%d" % index, center, 0, -95, 4.8, 150, 0.08)
    box("PM_Road_EW_%d" % index, 0, center, -95, 150, 4.8, 0.08)
    for side in (-1, 1):
        box("PM_Sidewalk_NS_%d_%d" % (index, side),
            center + side * 560, 0, -65, 1.5, 150, 0.18)
        box("PM_Sidewalk_EW_%d_%d" % (index, side),
            0, center + side * 560, -65, 150, 1.5, 0.18)

# Broken lane markings, leaving intersections clear.
for road_index, center in enumerate(road_centers):
    for segment in range(-13, 14):
        y = segment * 1050
        if abs(y - center) > 900:
            box("PM_Mark_NS_%d_%d" % (road_index, segment),
                center, y, -84, 0.10, 2.8, 0.025)
        x = segment * 1050
        if abs(x - center) > 900:
            box("PM_Mark_EW_%d_%d" % (road_index, segment),
                x, center, -84, 2.8, 0.10, 0.025)

# Crosswalk stripes around intersections.
for ix, cx in enumerate(road_centers):
    for iy, cy in enumerate(road_centers):
        for side in (-1, 1):
            for stripe in range(6):
                offset = (stripe - 2.5) * 115
                box("PM_Crosswalk_%d_%d_%d_%d" % (ix, iy, side, stripe),
                    cx + side * 650 + offset, cy + 650, -82, 0.42, 0.75, 0.025)
                box("PM_Crosswalk_%d_%d_%d_%d" % (ix, iy, side + 2, stripe),
                    cx + 650, cy + side * 650 + offset, -82, 0.75, 0.42, 0.025)

# Varied building massing in four blocks; all dimensions are Unreal centimeters.
block_centers = [-5000, 5000]
building_specs = [
    (-2100, -1800, 1150, 1250, 1700), (100, -1900, 1050, 1450, 2600),
    (2100, -1500, 900, 1300, 1250), (-1900, 300, 1300, 1100, 3100),
    (250, 350, 1450, 1250, 2100), (2050, 450, 950, 1150, 3900),
    (-1500, 2050, 1250, 1000, 1450), (650, 2100, 1150, 1150, 2350),
]
for bx in block_centers:
    for by in block_centers:
        for index, spec in enumerate(building_specs):
            dx, dy, half_x, half_y, height = spec
            box("PM_Building_%d_%d_%02d" % (bx, by, index),
                bx + dx, by + dy, -5 + height, half_x, half_y, height)

# Primitive placeholder street lamps.
for road in road_centers:
    for offset in (-8500, -3500, 3500, 8500):
        for side in (-1, 1):
            x, y = road + side * 760, offset
            spawn_mesh(cylinder, "PM_Lamp_Post", (x, y, 230), (0.12, 0.12, 3.0))
            spawn_mesh(cube, "PM_Lamp_Arm", (x + side * 115, y, 510), (1.3, 0.10, 0.10))

# Primitive placeholder trees.
for bx in block_centers:
    for by in block_centers:
        for dx, dy in [(-3000, -3000), (3000, 3000)]:
            x, y = bx + dx, by + dy
            spawn_mesh(cylinder, "PM_Tree_Trunk", (x, y, 170), (0.22, 0.22, 1.7))
            spawn_mesh(sphere, "PM_Tree_Canopy", (x, y, 500), (1.15, 1.15, 1.25))

# Player start and navigation bounds for later gameplay milestones.
start = actor_subsystem.spawn_actor_from_class(
    unreal.PlayerStart, unreal.Vector(-7200.0, -7200.0, 120.0), unreal.Rotator(0, 45, 0))
if start:
    start.set_actor_label("PM_PlayerStart")
    start.tags = list(start.tags) + [TAG]
    created += 1

nav_bounds = actor_subsystem.spawn_actor_from_class(
    unreal.NavMeshBoundsVolume, unreal.Vector(0.0, 0.0, 250.0), unreal.Rotator(0, 0, 0))
if nav_bounds:
    nav_bounds.set_actor_scale3d(unreal.Vector(150.0, 150.0, 5.0))
    nav_bounds.set_actor_label("PM_NavMeshBounds")
    nav_bounds.tags = list(nav_bounds.tags) + [TAG]
    created += 1

world = unreal.EditorLevelLibrary.get_editor_world()
saved = unreal.EditorLoadingAndSavingUtils.save_map(world, MAP_PACKAGE)
if not saved:
    unreal.log_warning("Project Mayhem: map save returned False. Use File > Save Current Level As and save to /Game/Maps/PM_FirstDistrict.")

unreal.log("Project Mayhem: first district blockout complete. Removed %d prior generated actors; created %d actors. Map saved: %s" % (removed, created, str(saved)))
